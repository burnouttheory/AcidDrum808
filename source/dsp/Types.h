#pragma once

// Core data model for blocks, tracks, notes, grids, and patterns.
// Mirrors the shapes used across the JavaScript codebase.

#include <cstdint>
#include <string>
#include <unordered_map>
#include <vector>

#include "RhythmEngine.h" // for Feel

namespace dgg {

// Track: a single instrument line, identified by a unique string key.
// The `role` drives articulation lookup and MIDI track naming; `gm` is the
// GM/SD3 note number written to note‑on/note‑off messages. `id` is the
// key used to index block data and must round‑trip with JSON project files.
struct Track {
  std::string id;
  std::string role;
  int         gm = 0;
  std::string name;
};

// A single note within a block. `beat` is relative to the block's own
// time signature and feel; `vel` is 1–127.
struct Note {
  double beat;
  int    vel;
  // True if this note was generated by a turnaround fill; used to exclude
  // fill notes when re‑reading the block's phrase source.
  bool   turnaround = false;
};

// Block: a self‑contained pattern with its own time signature, length, and
// note data per track.
struct Block {
  std::string id;
  std::string name;
  double      length    = 1.0;          // in bars
  int         numerator = 4;            // can differ from the global grid
  Feel        feel      = Feel::Straight;
  std::unordered_map<std::string, std::vector<Note>> data; // trackId → notes

  // Per‑engine‑group triplet‑layer ranges, consumed by generateTripletLayerBeats.
  // Each group (e.g. "kick") maps to a list of beat ranges.
  std::unordered_map<std::string, std::vector<BeatRange>> tripletLayers;

  // Stored seed per engine group. If absent for a group, a deterministic
  // fallback seed is used; once set, the stored value overrides it.
  std::unordered_map<std::string, uint32_t> seeds;

  // Pattern mode per engine group; absent means Classic.
  std::unordered_map<std::string, PatternMode> patternModes;
  std::unordered_map<std::string, std::string> patternFormulas; // expression for groups in Formula mode

  // Per‑sub‑group whitelist of enabled articulations. Sub‑groups are the
  // individual drum instruments (e.g. rackTom1, cymbal3). If missing or
  // empty for a sub‑group, the default set of enabled articulations is used.
  std::unordered_map<std::string, std::vector<std::string>> enabledArticulations;

  // ---- Turnaround / phrase / velocity‑build state ----
  // These fields are attached directly to the block object in the JavaScript
  // and are used by the turnaround and phrase‑length logic.
  std::unordered_map<std::string, int> phraseLength; // per group; absent → 1

  int    turnaroundInterval = 0; // 0 = off
  double velocityBuild      = 0.0;

  std::vector<std::string> turnaroundInstruments = {"snare"};
  double turnaroundDensity     = 50.0;
  double turnaroundSubdivision = 4.0;
  double turnaroundLengthBeats = 1.0;
  bool   turnaroundVaryPerOccurrence = false;
  int    turnaroundFillVel = 112;
  bool   turnaroundCrash   = true; // default true, can be opted out
  bool   turnaroundHiHat   = true; // false: the hi-hat is silent in the fill window

  double   turnaroundKickDensity     = 100.0;
  double   turnaroundKickSubdivision = 1.0;
  uint32_t turnaroundKickSeed        = 0; // default seed

  // The seed for the turnaround pattern itself. If not set, a fixed default
  // pattern is used; if set, a seeded variation is generated.
  bool     turnaroundSeedSet = false;
  uint32_t turnaroundSeed    = 0;

  // ---- Break state (for blocks that are "Break" blocks) ----
  // A Break block is identified by a non‑empty `breakParentId`; its
  // `breakBeats` are the trailing beats within `length` that form the break.
  std::string breakParentId;
  double      breakBeats = 0.0;

  std::vector<std::string> breakInstruments = {"toms"};
  double breakDensity     = 100.0;
  int    breakFillVel     = 112;
  double breakSubdivision = 4.0;

  double   breakKickDensity     = 100.0;
  double   breakKickSubdivision = 1.0;
  uint32_t breakKickSeed        = 0; // default seed (fixed arrangement)

  // If `breakSeedSet` is false, a fixed hand pattern is used; otherwise,
  // a seeded Euclidean‑based break fill is generated.
  bool     breakSeedSet = false;
  uint32_t breakSeed    = 0;

  // ---- Fill state (for Intro/Outro standalone blocks) ----
  bool        isFillBlock = false;
  double      fillBeats   = 0.0;
  std::string fillAnchor  = "end"; // "start" or "end"

  std::vector<std::string> fillInstruments = {"toms"};
  double fillDensity     = 100.0;
  int    fillVel         = 112;
  double fillSubdivision = 4.0;

  double   fillKickDensity     = 100.0;
  double   fillKickSubdivision = 1.0;
  uint32_t fillKickSeed        = 0; // default seed (fixed arrangement)

  // Same semantics as `breakSeedSet`/`breakSeed`.
  bool     fillSeedSet = false;
  uint32_t fillSeed    = 0;
};

// Grid: time signature and snap resolution for export and real‑time playback.
struct Grid {
  int    numerator   = 4;
  int    denominator = 4;
  double snap        = 0.25; // fraction of a beat; used for note‑off length
};

// Parameters for song/block export.
struct ExportParams {
  double      bpm     = 120.0;
  std::string kitName = "DGG-Generated";
  std::string genre   = "Custom";
};

// A single note event in a full pattern, with its absolute beat position.
struct PatternEvent {
  std::string trackId;
  double      beatAbs;
  int         vel;
  bool        accent = false;   // the Accent lane has a marker at this position (it applies to every instrument there)
};

// A complete pattern (song or block) as a flat list of events and total duration.
struct FullPattern {
  std::vector<PatternEvent> events;
  double                    totalBeats = 0.0;
};

// Builds a FullPattern from a single Block using the block's own numerator
// (which may differ from the global grid). The track list is passed separately.
FullPattern buildFullPatternFromBlock(const Block& block, const std::vector<Track>& tracks);

} // namespace dgg